export function dotMatrix(text, pitch = 5) {
  const cols = [];
  [...text.toUpperCase()].forEach((ch, i) => {
    const g = (F[ch] ?? F[' ']).split(' ');
    if (i) cols.push(null);
    for (let c = 0; c < g[0].length; c++) cols.push(g.map((row) => row[c] === '1'));
  });
  const r = pitch * 0.38;
  let dots = '';
  cols.forEach((col, x) => {
    for (let y = 0; y < 7; y++) {
      const lit = col?.[y];
      dots += `<circle cx="${x * pitch + pitch / 2}" cy="${y * pitch + pitch / 2}" r="${r}"${lit ? '' : ' opacity=".12"'}/>`;
    }
  });
  const w = cols.length * pitch;
  return `<svg width="${w}" height="${7 * pitch}" viewBox="0 0 ${w} ${7 * pitch}" fill="currentColor" aria-hidden="true">${dots}</svg>`;
}

export function renderDotMatrix(root = document) {
  root.querySelectorAll('[data-dm]').forEach((el) => {
    el.innerHTML = dotMatrix(el.dataset.dm, Number(el.dataset.pitch) || 5);
    el.setAttribute('role', 'img');
    el.setAttribute('aria-label', el.dataset.dm);
  });
}
